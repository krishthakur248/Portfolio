export function getCategoryIcon(categoryName) {
  const cat = (categoryName || '').toLowerCase();
  if (cat.includes('lang')) return LanguagesCategoryIcon;
  if (cat.includes('front')) return FrontendCategoryIcon;
  if (cat.includes('back')) return BackendCategoryIcon;
  if (cat.includes('data') && !cat.includes('struct')) return DatabasesCategoryIcon;
  if (cat.includes('fund') || cat.includes('cs') || cat.includes('struct')) return CsFundamentalsCategoryIcon;
  return ToolsCategoryIcon;
}

